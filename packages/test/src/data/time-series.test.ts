        it("IRI nodes have created_at and updated_at in UTC", async () => {
            const before = Date.now();
            await store.ensureNode(ctx, EX("foo"));
            const after = Date.now();

            const row = await trx("nodes")
                .where({ kind: "iri", iri: "http://example.org/foo" })
                .first<{ created_at: string; updated_at: string }>();

            expect(row).toBeDefined();
            const createdMs = new Date(row?.created_at).getTime();
            expect(createdMs).toBeGreaterThanOrEqual(before - CLOCK_SKEW_MS);
            expect(createdMs).toBeLessThanOrEqual(after + CLOCK_SKEW_MS);
            expect(row?.updated_at).toBeDefined();
        });

