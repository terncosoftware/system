    // ── Soft delete ───────────────────────────────────────────────────────────

    describe(`TripleStore — soft delete (${db.name})`, () => {
        let knex: Knex;
        let trx: Knex.Transaction;
        let store: TripleStore;
        let ctx: ServerContext;

        beforeEach(async () => {
            knex = await db.create();
            trx = await knex.transaction();
            store = new TripleStore(knex);
            ctx = buildServerContext(store, { trx });
        });
        afterEach(async () => {
            await trx.rollback();
            await assertEmptyStore(knex);
            await knex.destroy();
        });

        it("delete() marks the edge is_deleted=true and sets deleted_at", async () => {
            await store.insert(ctx, {
                subject: EX("s"),
                predicate: TYPE,
                object: EX("T"),
                graph: GRAPH,
            });
            const before = Date.now();
            const count = await store.delete(ctx, { subject: EX("s"), graph: GRAPH });
            const after = Date.now();

            expect(count).toBe(1);

            // Edge still exists in database (soft-delete, not hard-delete)
            const rows = await getEdgeById(trx as unknown as Knex, "http://example.org/s");
            expect(rows).toHaveLength(1);
            expect(!!rows[0].is_deleted).toBe(true); // SQLite returns 0/1
            const deletedMs = new Date(rows[0].deleted_at).getTime();
            expect(deletedMs).toBeGreaterThanOrEqual(before - CLOCK_SKEW_MS);
            expect(deletedMs).toBeLessThanOrEqual(after + CLOCK_SKEW_MS);
        });

        it("find() does not return soft-deleted edges", async () => {
            await store.insert(ctx, {
                subject: EX("s"),
                predicate: TYPE,
                object: EX("T"),
                graph: GRAPH,
            });
            await store.delete(ctx, { subject: EX("s"), graph: GRAPH });

            const quads = await store.find(ctx, { subject: EX("s"), graph: GRAPH });
            expect(quads).toHaveLength(0);
        });

        it("the node row is still present after soft-delete (no hard deletion)", async () => {
            const nodesBefore = await countNodes(trx as unknown as Knex);
            await store.insert(ctx, {
                subject: EX("s"),
                predicate: TYPE,
                object: EX("T"),
                graph: GRAPH,
            });
            const nodesAfterInsert = await countNodes(trx as unknown as Knex);
            await store.delete(ctx, { subject: EX("s"), graph: GRAPH });
            const nodesAfterDelete = await countNodes(trx as unknown as Knex);

            // Nodes never decrease
            expect(nodesAfterDelete).toBe(nodesAfterInsert);
            expect(nodesAfterInsert).toBeGreaterThan(nodesBefore);
        });

        it("stats().edges counts only active edges; edgesTotal includes deleted", async () => {
            const base = await store.stats(ctx);
            await store.insert(ctx, {
                subject: EX("s"),
                predicate: TYPE,
                object: EX("T"),
                graph: GRAPH,
            });
            await store.insert(ctx, {
                subject: EX("u"),
                predicate: TYPE,
                object: EX("T"),
                graph: GRAPH,
            });
            await store.delete(ctx, { subject: EX("s"), graph: GRAPH });

            const s = await store.stats(ctx);
            expect(s.edges - base.edges).toBe(1); // only EX('u') is active
            expect(s.edgesTotal - base.edgesTotal).toBe(2); // both rows exist in the table
        });

        it("delete returns 0 when no active edge matches", async () => {
            const count = await store.delete(ctx, { subject: EX("ghost"), graph: GRAPH });
            expect(count).toBe(0);
        });

        it("soft-deleting already-deleted edges does not double-count", async () => {
            const base = await countEdges(trx as unknown as Knex, true);
            await store.insert(ctx, {
                subject: EX("s"),
                predicate: TYPE,
                object: EX("T"),
                graph: GRAPH,
            });
            await store.delete(ctx, { subject: EX("s"), graph: GRAPH });
            const count2 = await store.delete(ctx, { subject: EX("s"), graph: GRAPH });
            expect(count2).toBe(0); // already deleted, no active edges remain
            expect((await countEdges(trx as unknown as Knex, true)) - base).toBe(1); // still only one row total
        });
    });

